#!/bin/bash
# Azure App Service (Linux) custom startup command.
# Set this file as the app's "Startup Command":
#   bash /home/site/wwwroot/deploy/startup.sh
#
# The deployed zip ships source only (no node_modules/.next/dist) -- `npm
# ci`/`npm run build` run right here, on the actual Linux App Service
# container. That's deliberate: running `npm ci` on a developer's Mac and
# shipping that node_modules to Linux breaks every package with a native
# binary (esbuild, Prisma's query engine, sharp, Next's SWC) because the
# installed binary matches the dev machine's OS/arch, not the server's.
# Installing here means the binaries always match the machine running them.
#
# Order matters: the gateway starts FIRST, before any install/build work.
# App Service kills a container that doesn't listen on $PORT within
# WEBSITES_CONTAINER_START_TIME_LIMIT, and installing+building on /home
# (network-mounted, slow) can exceed even the 1800s maximum. Listening
# immediately means the platform sees a healthy container and the build
# gets as long as it needs; the gateway answers 503 until the apps are up.
set -e

DEPLOY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$DEPLOY_DIR/.." && pwd)"

echo "[startup] wwwroot: $ROOT"

echo "[startup] starting gateway on port ${PORT:-8080}"
BACKEND_PORT=4000 FRONTEND_PORT=3000 node "$DEPLOY_DIR/gateway/server.js" &
GATEWAY_PID=$!

BACKEND_PID=""
FRONTEND_PID=""

cleanup() {
  echo "[startup] signal received, shutting down..."
  kill $GATEWAY_PID $BACKEND_PID $FRONTEND_PID 2>/dev/null || true
  wait $GATEWAY_PID $BACKEND_PID $FRONTEND_PID 2>/dev/null || true
}
trap cleanup SIGTERM SIGINT

# --include=dev: Azure sets NODE_ENV=production, which makes npm omit
#   devDependencies -- but the backend *runs* through tsx and the frontend
#   *builds* with typescript/tailwind, all of which live in devDependencies.
# --ignore-scripts: the backend's postinstall is `tsx scripts/bootstrap-db.ts`,
#   which (a) needs tsx before tsx is on disk, and (b) applies DB migrations.
#   Migrations are a deploy step, not a container-boot step -- run
#   `npx prisma migrate deploy` yourself against the prod DB. Prisma's own
#   client-generation postinstall is skipped too, so it runs explicitly below.
# Containers restart routinely (platform maintenance, idle recycles), and a
# full reinstall+rebuild is minutes of downtime each time. Stamp what was
# built and skip the work when the inputs haven't changed since.
# deploy-id is regenerated by build-package.sh for every package, so a new
# deploy always rebuilds -- source-only changes don't touch the lockfiles and
# would otherwise be served from a stale .next.
STAMP="$ROOT/.build-stamp"
CURRENT_STAMP="$(cat "$DEPLOY_DIR/deploy-id" "$ROOT/backend/package-lock.json" "$ROOT/frontend/package-lock.json" 2>/dev/null | shasum | cut -d' ' -f1)"

if [ -f "$STAMP" ] && [ "$(cat "$STAMP")" = "$CURRENT_STAMP" ] \
   && [ -d "$ROOT/backend/node_modules" ] && [ -d "$ROOT/frontend/.next" ]; then
  echo "[startup] dependencies + build up to date, skipping install/build"
else
  echo "[startup] installing backend dependencies (this can take several minutes)"
  (cd "$ROOT/backend" && npm ci --include=dev --ignore-scripts && npx prisma generate)

  # .next is built by build-package.sh and ships in the zip, so normally only
  # the runtime dependencies are needed here. The build is kept as a fallback
  # for a package that somehow arrived without it.
  if [ -d "$ROOT/frontend/.next" ]; then
    echo "[startup] installing frontend runtime dependencies (.next shipped prebuilt)"
    (cd "$ROOT/frontend" && npm ci --omit=dev)
  else
    echo "[startup] no prebuilt .next found -- installing and building frontend"
    (cd "$ROOT/frontend" && npm ci --include=dev && npm run build)
  fi

  echo "$CURRENT_STAMP" > "$STAMP"
fi

# Applies any migrations the deployed code expects but the database hasn't
# got yet. Idempotent -- a database already at the latest migration is a
# no-op -- so it runs on every boot rather than only on rebuilds, which is
# what makes a code-only redeploy pick up its migrations. Deliberately not
# fatal: if the database is briefly unreachable we still want the gateway
# and frontend serving rather than the whole container dying.
echo "[startup] applying database migrations"
(cd "$ROOT/backend" && npx prisma migrate deploy) \
  || echo "[startup] WARNING: prisma migrate deploy failed -- backend may not start"

echo "[startup] starting backend (Fastify) on 127.0.0.1:4000"
# Run via tsx (same as `npm run dev`) rather than compiling with tsc: the
# source uses the "@/*" tsconfig alias and extensionless relative imports,
# both of which tsx resolves the same way it already does in dev, and
# neither of which Node's strict ESM resolver accepts on plain compiled JS.
(cd "$ROOT/backend" && PORT=4000 NODE_ENV=production node node_modules/tsx/dist/cli.mjs src/index.ts) &
BACKEND_PID=$!

echo "[startup] starting frontend (Next.js) on 127.0.0.1:3000"
(cd "$ROOT/frontend" && PORT=3000 NODE_ENV=production node node_modules/next/dist/bin/next start -H 0.0.0.0 -p 3000) &
FRONTEND_PID=$!

echo "[startup] all processes launched; gateway pid=$GATEWAY_PID backend pid=$BACKEND_PID frontend pid=$FRONTEND_PID"
wait $GATEWAY_PID
